/* eslint-env jest */
import React from 'react';
import {act, create} from 'react-test-renderer';
import {ActivityIndicator, Alert, FlatList, Image, Linking, Text, TouchableOpacity} from 'react-native';
import BannerSlider from '../src/components/BannerSlider';
import {useGetBannersQuery} from '../src/redux/api';

jest.mock('react-native-vector-icons/Ionicons', () => 'Icon');
jest.mock('../src/redux/api', () => ({useGetBannersQuery: jest.fn()}));
const banner = {BANCODE: 51, BNAME: 'new banner', BURL: null, IMG: 'new_banner_51.jpg', PLACEMENT: 'Top', APAGE: 'Index', APP: 'User'};
const load = data => useGetBannersQuery.mockReturnValue({data: {success: true, data}});
beforeEach(() => {jest.useFakeTimers(); jest.clearAllMocks(); load([banner]);});
afterEach(() => {jest.clearAllTimers(); jest.useRealTimers();});
const button = (tree, label) => tree.root.findAllByType(TouchableOpacity).find(node => node.props.accessibilityLabel === label);
test('uses exact backend fields and shows a placeholder without inventing an image URL or link', async () => {
  let tree;
  await act(async () => {tree = create(<BannerSlider />);});
  expect(tree.root.findByType(FlatList).props.data).toEqual([banner]);
  expect(tree.root.findByType(FlatList).props.keyExtractor(banner)).toBe('51');
  expect(tree.root.findAllByType(Text).some(node => node.props.children === banner.BNAME)).toBe(true);
  expect(tree.root.findAllByType(Image)).toHaveLength(0);
  expect(button(tree, 'new banner').props.disabled).toBe(true);
  expect(button(tree, 'Next banner')).toBeUndefined();
  await act(async () => tree.unmount());
});
test('uses complete IMG and BURL values exactly and handles image/link failures', async () => {
  const IMG = 'https://example.invalid/banner.jpg';
  const BURL = 'https://example.invalid/offer';
  const open = jest.spyOn(Linking, 'openURL').mockRejectedValue(new Error('Unavailable'));
  const alert = jest.spyOn(Alert, 'alert').mockImplementation(() => {});
  load([{...banner, IMG, BURL}]);
  let tree;
  await act(async () => {tree = create(<BannerSlider />);});
  expect(tree.root.findByType(Image).props.source).toEqual({uri: IMG});
  await act(async () => button(tree, 'new banner').props.onPress());
  expect(open).toHaveBeenCalledWith(BURL);
  expect(alert).toHaveBeenCalledWith('Could not open banner', 'Please try again.');
  await act(async () => tree.root.findByType(Image).props.onError());
  expect(tree.root.findAllByType(Image)).toHaveLength(0);
  await act(async () => tree.unmount());
  open.mockRestore(); alert.mockRestore();
});
test('only displays Top/Index/User banners and wraps carousel controls', async () => {
  const second = {...banner, BANCODE: 52};
  load([banner, second, {...banner, BANCODE: 53, PLACEMENT: 'Bottom'}, {...banner, BANCODE: 54, APAGE: 'Other'}, {...banner, BANCODE: 55, APP: 'Admin'}, null]);
  let tree;
  await act(async () => {tree = create(<BannerSlider />);});
  const list = tree.root.findByType(FlatList);
  expect(list.props.data).toEqual([banner, second]);
  const scroll = jest.spyOn(list.instance, 'scrollToIndex').mockImplementation(() => {});
  await act(async () => button(tree, 'Next banner').props.onPress());
  expect(scroll).toHaveBeenLastCalledWith({index: 1, animated: true});
  await act(async () => list.props.onViewableItemsChanged({viewableItems: [{index: 1}]}));
  await act(async () => jest.advanceTimersByTime(3000));
  expect(scroll).toHaveBeenLastCalledWith({index: 0, animated: true});
  await act(async () => button(tree, 'Previous banner').props.onPress());
  expect(scroll).toHaveBeenLastCalledWith({index: 0, animated: true});
  await act(async () => tree.unmount());
});
test('shows loading and retry, then handles empty or shrinking results', async () => {
  const refetch = jest.fn();
  useGetBannersQuery.mockReturnValue({isLoading: true});
  let tree;
  await act(async () => {tree = create(<BannerSlider />);});
  expect(tree.root.findByType(ActivityIndicator).props.accessibilityLabel).toBe('Loading banners');
  useGetBannersQuery.mockReturnValue({data: {success: false}, refetch});
  await act(async () => tree.update(<BannerSlider />));
  await act(async () => button(tree, 'Retry banners').props.onPress());
  expect(refetch).toHaveBeenCalledTimes(1);
  load([banner, {...banner, BANCODE: 52}]);
  await act(async () => tree.update(<BannerSlider />));
  await act(async () => tree.root.findByType(FlatList).props.onViewableItemsChanged({viewableItems: [{index: 1}]}));
  load([banner]);
  await act(async () => tree.update(<BannerSlider />));
  expect(button(tree, 'Next banner')).toBeUndefined();
  load([]);
  await act(async () => tree.update(<BannerSlider />));
  expect(tree.toJSON()).toBeNull();
  await act(async () => tree.unmount());
});
